// Run once in Edit mode. Extend only the Result scene; never rebuild the exhibit.
if (Application.isPlaying || UnityEngine.SceneManagement.SceneManager.GetActiveScene().isDirty)
    throw new Exception("Stop Play mode and preserve pending scene edits first.");
var library = AssetDatabase.LoadAssetAtPath<Exhibition.UI.ExhibitionUIAssets>("Assets/UI/ExhibitionUIAssets.asset");
var entries = new System.Collections.Generic.List<Exhibition.UI.ExhibitionUIAssets.Entry>(library.sprites);
foreach (string code in new[] { "en", "th" })
{
    string path = "Assets/UI/UIs_" + (code == "en" ? "En" : "Th") + "/Video/VideoHomeHint_" + code + ".png";
    var importer = (TextureImporter)AssetImporter.GetAtPath(path);
    importer.textureType = TextureImporterType.Sprite;
    importer.spriteImportMode = SpriteImportMode.Single;
    importer.mipmapEnabled = false;
    importer.alphaIsTransparency = true;
    importer.npotScale = TextureImporterNPOTScale.None;
    importer.textureCompression = TextureImporterCompression.Uncompressed;
    importer.wrapMode = TextureWrapMode.Clamp;
    importer.maxTextureSize = 2048;
    importer.SaveAndReimport();
    string id = "VideoHomeHint_" + code;
    entries.RemoveAll(e => e.id == id);
    entries.Add(new Exhibition.UI.ExhibitionUIAssets.Entry { id = id, sprite = AssetDatabase.LoadAssetAtPath<Sprite>(path) });
}
library.sprites = entries.ToArray();
library.defaultThai = System.IO.File.ReadAllText("Assets/StreamingAssets/Lang_Th.json");
library.defaultEnglish = System.IO.File.ReadAllText("Assets/StreamingAssets/Lang_En.json");
EditorUtility.SetDirty(library);
AssetDatabase.SaveAssetIfDirty(library);
const string scenePath = "Assets/Scenes/2_Result.unity";
System.IO.File.Copy(scenePath, "docs/validation/ui_web4/before/2_Result.unity", true);
var scene = UnityEditor.SceneManagement.EditorSceneManager.OpenScene(scenePath);
var localization = UnityEngine.Object.FindFirstObjectByType<Exhibition.UI.LocalizedImageSet>();
var controller = UnityEngine.Object.FindFirstObjectByType<Exhibition.UI.ResultVideoController>();
var video = localization.transform.Find("ExplanationVideo");
if (video.Find("PlaybackLocalizedImages")) throw new Exception("Video hint already authored.");
var layer = new GameObject("PlaybackLocalizedImages", typeof(RectTransform), typeof(CanvasGroup));
var rect = (RectTransform)layer.transform;
rect.SetParent(video, false);
rect.anchorMin = Vector2.zero;
rect.anchorMax = Vector2.one;
rect.offsetMin = rect.offsetMax = Vector2.zero;
rect.SetAsFirstSibling();
var group = layer.GetComponent<CanvasGroup>();
group.interactable = group.blocksRaycasts = false;
var hint = new GameObject("VideoHomeHint_th", typeof(RectTransform), typeof(UnityEngine.UI.Image));
var hintRect = (RectTransform)hint.transform;
hintRect.SetParent(rect, false);
hintRect.anchorMin = hintRect.anchorMax = hintRect.pivot = new Vector2(0, 1);
hintRect.anchoredPosition = new Vector2(40, -40);
hintRect.sizeDelta = new Vector2(452, 94);
var image = hint.GetComponent<UnityEngine.UI.Image>();
image.sprite = library.Find("VideoHomeHint_th");
image.preserveAspect = true;
image.raycastTarget = false;
hint.SetActive(false);
var serialized = new SerializedObject(localization);
var bindings = serialized.FindProperty("bindings");
int index = bindings.arraySize;
bindings.InsertArrayElementAtIndex(index);
var binding = bindings.GetArrayElementAtIndex(index);
binding.FindPropertyRelative("id").stringValue = "video.home";
binding.FindPropertyRelative("image").objectReferenceValue = image;
var groups = serialized.FindProperty("localizedGroups");
index = groups.arraySize;
groups.InsertArrayElementAtIndex(index);
groups.GetArrayElementAtIndex(index).objectReferenceValue = group;
serialized.ApplyModifiedPropertiesWithoutUndo();
serialized = new SerializedObject(controller);
serialized.FindProperty("playbackHint").objectReferenceValue = hint;
serialized.ApplyModifiedPropertiesWithoutUndo();
UnityEditor.SceneManagement.EditorSceneManager.MarkSceneDirty(scene);
UnityEditor.SceneManagement.EditorSceneManager.SaveScene(scene);
UnityEditor.SceneManagement.EditorSceneManager.OpenScene("Assets/Scenes/0_Idle.unity");
return "Authored noninteractive bilingual video home hint at (40,40). Existing media/input/presentation references preserved.";
