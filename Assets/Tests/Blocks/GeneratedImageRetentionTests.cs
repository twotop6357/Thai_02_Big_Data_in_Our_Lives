using System;
using System.IO;
using System.Threading;
using Exhibition.Blocks;
using NUnit.Framework;

public sealed class GeneratedImageRetentionTests
{
    private string _root, _folder;
    private readonly DateTime _now = new DateTime(2026, 10, 19, 0, 0, 0, DateTimeKind.Utc);

    [SetUp] public void CreateIsolatedOutput()
    {
        _root = Path.Combine(Path.GetTempPath(), "Thai02RetentionTests_" + Guid.NewGuid().ToString("N"));
        _folder = Path.Combine(_root, "Thai02");
        Directory.CreateDirectory(_folder);
    }

    [TearDown] public void RemoveIsolatedOutput()
    {
        // This directory is generated by this test; never recurse into a supplied/output-server path.
        if (Directory.Exists(_root)) Directory.Delete(_root, true);
    }

    private string Image(int id, int bytes = 100, int ageSeconds = 120)
    {
        string file = Path.Combine(_folder, "blocks_" + id.ToString("x32") + "_00001_.png");
        File.WriteAllBytes(file, new byte[bytes]);
        File.SetLastWriteTimeUtc(file, _now.AddSeconds(-ageSeconds));
        return file;
    }

    private ImageRetentionReport Sweep(int count, long bytes = 10000, string active = null) =>
        GeneratedImageRetentionPolicy.Sweep(_root, count, bytes, TimeSpan.FromSeconds(60), _now, active);

    [TestCase(2, 10000, 1)]
    [TestCase(10, 150, 2)]
    [TestCase(2, 150, 2)]
    public void RestoresCountAndByteLimitsOldestFirst(int count, long bytes, int deleted)
    {
        string oldest = Image(1, ageSeconds: 300);
        string middle = Image(2, ageSeconds: 200);
        string newest = Image(3, ageSeconds: 100);
        var report = Sweep(count, bytes);
        Assert.IsTrue(report.WithinLimits);
        Assert.AreEqual(deleted, report.DeletedFiles);
        Assert.IsFalse(File.Exists(oldest));
        Assert.IsTrue(File.Exists(newest));
        Assert.AreEqual(deleted == 1, File.Exists(middle));
        Assert.AreEqual(300 - deleted * 100, report.RemainingBytes);
    }

    [Test] public void BelowLimitsDoesNotDeleteAnything()
    {
        string file = Image(1);
        var report = Sweep(1);
        Assert.AreEqual(0, report.DeletedFiles);
        Assert.IsTrue(report.WithinLimits);
        Assert.IsTrue(File.Exists(file));
    }

    [Test] public void ForwardSlashAbsolutePathIsSupported()
    {
        Image(1);
        var report = GeneratedImageRetentionPolicy.Sweep(_root.Replace('\\', '/'), 1, 10000,
            TimeSpan.FromSeconds(60), _now);
        Assert.IsTrue(report.WithinLimits);
        Assert.AreEqual(1, report.RemainingFiles);
    }

    [Test] public void RecentWritesSurviveEvenWhenOverLimit()
    {
        string a = Image(1, ageSeconds: 10), b = Image(2, ageSeconds: 20);
        var report = Sweep(1);
        Assert.IsFalse(report.WithinLimits);
        Assert.IsTrue(File.Exists(a) && File.Exists(b));
        var later = GeneratedImageRetentionPolicy.Sweep(_root, 1, 10000, TimeSpan.FromSeconds(60), _now.AddMinutes(2));
        Assert.IsTrue(later.WithinLimits);
        Assert.IsTrue(File.Exists(a));
        Assert.IsFalse(File.Exists(b));
    }

    [Test] public void ActiveRequestIsProtectedRegardlessOfFileAge()
    {
        string active = Image(1, ageSeconds: 500), other = Image(2);
        var report = Sweep(1, active: 1.ToString("x32"));
        Assert.IsTrue(report.WithinLimits);
        Assert.IsTrue(File.Exists(active));
        Assert.IsFalse(File.Exists(other));
    }

    [Test] public void ForeignFilesAndNestedDirectoriesAreNeverDeleted()
    {
        string foreign = Path.Combine(_folder, "product_00001_.png");
        string fake = Path.Combine(_folder, "blocks_family_photo.png");
        File.WriteAllText(foreign, "keep");
        File.WriteAllText(fake, "keep");
        string nested = Path.Combine(_folder, "nested");
        Directory.CreateDirectory(nested);
        string nestedFile = Path.Combine(nested, "blocks_" + 9.ToString("x32") + "_00001_.png");
        File.WriteAllText(nestedFile, "keep");
        string parent = Path.Combine(_root, "blocks_" + 9.ToString("x32") + "_00001_.png");
        File.WriteAllText(parent, "keep");
        Image(1, ageSeconds: 300); Image(2);
        var report = Sweep(1);
        Assert.AreEqual(1, report.DeletedFiles);
        foreach (var file in new[] { foreign, fake, nestedFile, parent }) Assert.IsTrue(File.Exists(file));
    }

    [Test] public void LockedFileIsReportedAndOtherFilesCanBePruned()
    {
        string locked = Image(1, ageSeconds: 300), other = Image(2);
        using (var stream = new FileStream(locked, FileMode.Open, FileAccess.Read, FileShare.None))
        {
            var report = Sweep(1);
            Assert.AreEqual(1, report.FailedDeletes);
            Assert.IsTrue(report.WithinLimits);
            Assert.IsFalse(File.Exists(other));
        }
        Assert.IsTrue(File.Exists(locked));
    }

    [Test] public void CancellationStopsBeforeDeletingAnyFile()
    {
        string a = Image(1), b = Image(2);
        Assert.Throws<OperationCanceledException>(() => GeneratedImageRetentionPolicy.Sweep(_root, 1, 1,
            TimeSpan.Zero, _now, token: new CancellationToken(true)));
        Assert.IsTrue(File.Exists(a) && File.Exists(b));
    }

    [Test] public void InvalidRootsAndLimitsAreRejectedBeforeDeletion()
    {
        string file = Image(1);
        Assert.Throws<ArgumentException>(() => GeneratedImageRetentionPolicy.ValidateOutputDirectory("relative/output"));
        Assert.Throws<ArgumentException>(() => GeneratedImageRetentionPolicy.ValidateOutputDirectory("C:relative"));
        Assert.Throws<ArgumentException>(() => GeneratedImageRetentionPolicy.ValidateOutputDirectory(Path.GetPathRoot(_root)));
        Assert.Throws<ArgumentOutOfRangeException>(() => Sweep(0));
        Assert.IsTrue(File.Exists(file));
    }

    [TestCase("blocks_0123456789abcdef0123456789abcdef_00001_.png", true)]
    [TestCase("blocks_0123456789abcdef0123456789abcdef_00001_.png.bak", false)]
    [TestCase("blocks_not-a-guid_00001_.png", false)]
    [TestCase("../blocks_0123456789abcdef0123456789abcdef_00001_.png", false)]
    public void OnlyExactProjectOutputNamesMatch(string name, bool owned) =>
        Assert.AreEqual(owned, GeneratedImageRetentionPolicy.IsOwnedName(name));
}
